'use client';

import { useMemo, useState, useCallback } from 'react';
import { useRouter } from 'next/navigation';
import { Table, TableBody, TableCell, TableHeader, TableRow } from '@/components/ui/table';
import { SortableTableHead, SortDirection } from '@/components/ui/sortable-table-head';
import { ConfirmationDialog } from '@/components/ui/confirmation-dialog';
import { Eye, Pencil, RefreshCcw, Trash2 } from 'lucide-react';
import { useAuthStore } from '@/lib/store/auth-store';
import ROLES from '@/constants/roles';
import { sortData } from '@/lib/utils/table-sort';

export interface Quote {
  id: string;
  vin: string;
  customer: string;
  generatedBy: string;
  vehicle: string;
  date: string;
  total: string;
}

interface QuotesTableProps {
  quotes: Quote[];
  onDelete?: (id: string) => void;
  onResend?: (id: string) => void;
  onView?: (id: string) => void;
  pageSize?: number;
  currentPage?: number;
  source?: 'saved-quotes' | 'dashboard';
}

export function QuotesTable({ quotes, onDelete, onResend, onView, pageSize = 10, currentPage = 1, source }: QuotesTableProps) {
  const router = useRouter();
  const { user } = useAuthStore();
  const [sortKey, setSortKey] = useState<string | null>(null);
  const [sortDirection, setSortDirection] = useState<SortDirection>(null);

  // Determine basePath from user role
  const basePath = useMemo(() => {
    if (user?.role === ROLES.BUSINESS_OWNER) {
      return '/business';
    }
    if (user?.role === ROLES.STAFF) {
      return '/staff';
    }
    return '/business'; // Default fallback
  }, [user?.role]);

  const handleSort = useCallback((key: string, direction: SortDirection) => {
    setSortKey(direction ? key : null);
    setSortDirection(direction);
  }, []);

  const getValue = useCallback((item: Quote, key: string) => {
    return item[key as keyof Quote];
  }, []);

  // Sort data
  const sortedQuotes = useMemo(() => {
    return sortData(quotes, sortKey, sortDirection, getValue);
  }, [quotes, sortKey, sortDirection, getValue]);

  const handleDelete = (id: string) => {
    onDelete?.(id);
  };

  const handleView = (id: string) => {
    if (onView) {
      onView(id);
    } else {
      const url = source ? `${basePath}/quotes/${id}?source=${source}` : `${basePath}/quotes/${id}`;
      router.push(url);
    }
  };

  const handleResend = (id: string) => {
    if (onResend) {
      onResend(id);
      router.push(`${basePath}/lookup/details/view?source=saved-quotes`);
    } else {
      console.log('Resend quote:', id);
    }
  };

  const handleEdit = () => {
    router.push(`${basePath}/lookup/details/view?source=dashboard`);
  };

  // Pagination logic
  const startIndex = (currentPage - 1) * pageSize;
  const endIndex = startIndex + pageSize;
  const paginatedQuotes = sortedQuotes.slice(startIndex, endIndex);

  return (
    <div className="overflow-x-auto border border-gray-200 rounded-sm px-6">
      <Table>
        <TableHeader>
          <TableRow className="border-gray-200">
            <SortableTableHead sortKey="id" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary text-left px-0">
              Quote ID
            </SortableTableHead>
            <SortableTableHead sortKey="vin" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              VIN No.
            </SortableTableHead>
            <SortableTableHead sortKey="customer" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              Customer
            </SortableTableHead>
            <SortableTableHead sortKey="generatedBy" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              Generated By
            </SortableTableHead>
            <SortableTableHead sortKey="vehicle" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              Vehicle
            </SortableTableHead>
            <SortableTableHead sortKey="date" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              Date
            </SortableTableHead>
            <SortableTableHead sortKey="total" currentSortKey={sortKey} sortDirection={sortDirection} onSort={handleSort} className="font-semibold text-lg text-primary">
              Total
            </SortableTableHead>
            <SortableTableHead className="font-semibold text-lg text-primary">Actions</SortableTableHead>
          </TableRow>
        </TableHeader>
        <TableBody>
          {paginatedQuotes.length > 0 ? (
            paginatedQuotes.map(q => (
              <TableRow key={q.id} className="border-gray-200">
                <TableCell className="text-secondary text-left px-0">{q.id}</TableCell>
                <TableCell className="text-secondary">{q.vin}</TableCell>
                <TableCell className="text-secondary">{q.customer}</TableCell>
                <TableCell className="text-secondary">{q.generatedBy}</TableCell>
                <TableCell className="text-secondary">{q.vehicle}</TableCell>
                <TableCell className="text-secondary">{q.date}</TableCell>
                <TableCell className="text-secondary">{q.total}</TableCell>
                <TableCell className="text-secondary">
                  <div className="flex items-center gap-2">
                    {/* Resend Quote */}
                    <ConfirmationDialog
                      trigger={
                        <button className="cursor-pointer p-2 rounded-lg border border-gray-300 bg-white hover:bg-gray-50">
                          <RefreshCcw className="w-4 h-4 text-gray-600" />
                        </button>
                      }
                      icon={{ src: '/images/icons/humbleicons_refresh_white.svg', alt: 'Resend', bgColor: 'bg-[#54C27D]' }}
                      title="Are you sure you want to resend?"
                      description="If you resend now, the request will be sent again and may duplicate the previous action."
                      confirmButtonText="Yes"
                      cancelButtonText="No"
                      buttonOrder="reversed"
                      onConfirm={() => handleResend(q.id)}
                      onCancel={() => {}}
                    />
                    <button onClick={() => handleView(q.id)} className="cursor-pointer p-2 rounded-lg border border-gray-300 bg-white hover:bg-gray-50">
                      <Eye className="w-4 h-4 text-gray-600" />
                    </button>
                    <button onClick={handleEdit} className="cursor-pointer p-2 rounded-lg border border-gray-300 bg-white hover:bg-gray-50">
                      <Pencil className="w-4 h-4 text-gray-600" />
                    </button>

                    <ConfirmationDialog
                      trigger={
                        <button className="p-2 rounded-lg border border-gray-300 bg-white hover:bg-gray-50 hover:cursor-pointer transition-colors">
                          <Trash2 className="w-4 h-4 text-red-500" />
                        </button>
                      }
                      icon={{ src: '/images/icons/delete-white.svg', alt: 'Delete', bgColor: 'bg-red-primary' }}
                      title="Are you sure you want to delete?"
                      description="If you delete now, this item will be permanently removed and cannot be recovered."
                      confirmButtonText="Yes"
                      cancelButtonText="No"
                      onConfirm={() => handleDelete(q.id)}
                      onCancel={() => {}}
                      buttonOrder="reversed"
                    />
                  </div>
                </TableCell>
              </TableRow>
            ))
          ) : (
            <TableRow>
              <TableCell colSpan={8} className="text-center text-secondary h-24">
                No Data Found
              </TableCell>
            </TableRow>
          )}
        </TableBody>
      </Table>
    </div>
  );
}
