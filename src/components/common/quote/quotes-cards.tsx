'use client';

import { useRouter } from 'next/navigation';
import { Eye, Trash2 } from 'lucide-react';
import { ConfirmationDialog } from '@/components/ui/confirmation-dialog';
import { Button } from '@/components/ui/button';
import { useAuthStore } from '@/lib/store/auth-store';
import ROLES from '@/constants/roles';
import { useMemo } from 'react';
import type { Quote } from './quotes-table';
import Image from 'next/image';

interface QuotesCardsProps {
  quotes: Quote[];
  onDelete?: (id: string) => void;
  onResend?: (id: string) => void;
  onView?: (id: string) => void;
  source?: 'saved-quotes' | 'dashboard';
}

export function QuotesCards({ quotes, onDelete, onResend, onView, source }: QuotesCardsProps) {
  const router = useRouter();
  const { user } = useAuthStore();

  // Determine basePath from user role
  const basePath = useMemo(() => {
    if (user?.role === ROLES.BUSINESS_OWNER) {
      return '/business';
    }
    if (user?.role === ROLES.STAFF) {
      return '/staff';
    }
    return '/business'; // Default fallback
  }, [user?.role]);

  const handleDelete = (id: string) => {
    onDelete?.(id);
  };

  const handleView = (id: string) => {
    if (onView) {
      onView(id);
    } else {
      const url = source ? `${basePath}/quotes/${id}?source=${source}` : `${basePath}/quotes/${id}`;
      router.push(url);
    }
  };

  const handleResend = (id: string) => {
    if (onResend) {
      onResend(id);
      router.push(`${basePath}/lookup/details/view?source=saved-quotes`);
    } else {
      console.log('Resend quote:', id);
    }
  };

  if (quotes.length === 0) {
    return (
      <div className="text-center text-secondary py-12">
        <p>No Data Found</p>
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {quotes.map(quote => (
        <div key={quote.id} className="bg-white rounded-lg border border-gray-200 p-4 shadow-sm">
          {/* Quote Information - Two Column Layout */}
          <div className="grid grid-cols-2 gap-4 mb-4">
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Quote ID</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.id}</p>
            </div>
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">VIN No.</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.vin}</p>
            </div>
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Customer</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.customer}</p>
            </div>
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Date</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.date}</p>
            </div>
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Generated By</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.generatedBy}</p>
            </div>

            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Vehicle</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.vehicle}</p>
            </div>
            <div>
              <p className="text-xs font-normal text-[#6A7282] mb-1">Total</p>
              <p className="text-sm font-normal text-[#2C2C2C] break-words">{quote.total}</p>
            </div>
          </div>

          {/* Action Buttons */}
          <div className="flex items-center gap-2  ">
            <ConfirmationDialog
              trigger={
                <Button className="h-[26px] flex-1 flex items-center gap-2 bg-blue-primary hover:bg-blue-primary/90 text-white px-4 rounded-sm text-xs font-normal">
                  <Image src="/images/icons/refresh.svg" alt="Resend" width={14} height={14} />
                  Resend
                </Button>
              }
              icon={{ src: '/images/icons/humbleicons_refresh_white.svg', alt: 'Resend', bgColor: 'bg-[#54C27D]' }}
              title="Are you sure you want to resend?"
              description="If you resend now, the request will be sent again and may duplicate the previous action."
              confirmButtonText="Yes"
              cancelButtonText="No"
              buttonOrder="reversed"
              onConfirm={() => handleResend(quote.id)}
              onCancel={() => {}}
            />
            <div className="flex items-center gap-1">
              {/* Delete Button - Red square */}
              <ConfirmationDialog
                trigger={
                  <button className="px-4 h-[26px] rounded-sm border border-gray-300 bg-white hover:bg-gray-50 hover:cursor-pointer transition-colors">
                    <Trash2 className="w-4 h-4 text-red-500" />
                  </button>
                }
                icon={{ src: '/images/icons/delete-white.svg', alt: 'Delete', bgColor: 'bg-red-primary' }}
                title="Are you sure you want to delete?"
                description="If you delete now, this item will be permanently removed and cannot be recovered."
                confirmButtonText="Yes"
                cancelButtonText="No"
                onConfirm={() => handleDelete(quote.id)}
                onCancel={() => {}}
                buttonOrder="reversed"
              />

              {/* View Button - Gray square */}
              <button onClick={() => handleView(quote.id)} className="px-4 h-[26px] rounded-sm border border-gray-300 bg-white hover:bg-gray-50 hover:cursor-pointer transition-colors">
                <Eye className="w-4 h-4 text-gray-600" />
              </button>
            </div>
          </div>
        </div>
      ))}
    </div>
  );
}
